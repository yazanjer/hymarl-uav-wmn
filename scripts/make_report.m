function make_report(tag)
%MAKE_REPORT  Turn a real headline_<tag>.mat run into thesis-ready artefacts:
%   convergence figure, per-metric boxplots, and booktabs LaTeX result tables for
%   Chapter 4 (routing), Chapter 5 (interference) and Chapter 6 (user experience),
%   each with mean±SD, Bonferroni-corrected Wilcoxon p and rank-biserial effect
%   size (thesis Sec.3.5.2.5). ALL numbers come from the real .mat.
if nargin<1, tag='A8'; end
here=fileparts(mfilename('fullpath'));
resdir=fullfile(here,'..','results');
thesis=fullfile(here,'..','output'); if ~exist(thesis,'dir'), mkdir(thesis); end;
figdir=fullfile(thesis,'figures'); if ~exist(figdir,'dir'), mkdir(figdir); end
L=load(fullfile(resdir,sprintf('headline_%s.mat',tag))); R=L.R;
Data=R.Data; methods=R.methods; mn=R.metricNames; S=size(Data,1);

% ---------- convergence figure ----------
f1=figure('Visible','off','Position',[100 100 560 380]); hold on;
cols=lines(numel(methods)); lg={};
for mi=1:numel(methods)
  if isempty(R.curves{mi}), continue; end
  plot(movmean(R.curves{mi},3),'LineWidth',1.6,'Color',cols(mi,:));
  lg{end+1}=methods{mi}; %#ok<AGROW>
end
grid on; xlabel('Training episode'); ylabel('Mean per-agent return');
title('Convergence (Scenario A, N=10)'); legend(lg,'Location','southeast');
exportgraphics(f1,fullfile(figdir,'ch4_convergence.pdf'),'ContentType','vector');

% ---------- boxplots (4 headline metrics) ----------
show={'delay','throughput','pdr','fairness'};
lab={'End-to-end delay (ms)','Throughput (Mbps)','PDR','Jain fairness'};
f2=figure('Visible','off','Position',[100 100 820 560]);
for si=1:4
  k=find(strcmp(mn,show{si})); subplot(2,2,si);
  boxplot(squeeze(Data(:,:,k)),'Labels',methods); grid on; title(lab{si});
end
exportgraphics(f2,fullfile(figdir,'ch4_boxplots.pdf'),'ContentType','vector');

% ---------- three chapter tables ----------
pretty=containers.Map(...
 {'delay','pdr','throughput','fairness','loadVar','cci','specEff','energyPerBit','chanUtil','handover','sinr_mean'},...
 {'End-to-end delay (ms) $\downarrow$','PDR $\uparrow$','Throughput (Mbps) $\uparrow$',...
  'Jain fairness $\uparrow$','Load variance $\downarrow$','CCI (dBm) $\downarrow$',...
  'Spectral eff.\ (bps/Hz) $\uparrow$','Energy/bit ($\mu$J) $\downarrow$',...
  'Router utilisation','Handover / user $\downarrow$','Mean SINR (dB) $\uparrow$'});
writeTable(fullfile(thesis,'ch4_results.tex'),R,mn,methods,pretty,S,tag,...
  {'delay','pdr','throughput','fairness','loadVar','energyPerBit'},...
  'ch4_headline','Scenario~A headline routing results at $N=10$');
writeTable(fullfile(thesis,'ch5_results.tex'),R,mn,methods,pretty,S,tag,...
  {'cci','specEff','chanUtil','throughput','sinr_mean'},...
  'ch5_interf','Scenario~A multi-channel / interference results at $N=10$');
writeTable(fullfile(thesis,'ch6_results.tex'),R,mn,methods,pretty,S,tag,...
  {'loadVar','fairness','handover','delay'},...
  'ch6_load','Scenario~A load-aware assignment results at $N=10$');
fprintf('make_report: wrote figures + ch4/ch5/ch6 result tables from headline_%s.mat (S=%d)\n',tag,S);
end

function writeTable(fpath,R,mn,methods,pretty,S,tag,metrics,label,caption)
Data=R.Data; pIdx=find(strcmp(methods,'Proposed'));
b1=find(strcmp(methods,'B1')); b2=find(strcmp(methods,'B2'));
fid=fopen(fpath,'w');
fprintf(fid,'%% Auto-generated by make_report.m from real run headline_%s.mat (S=%d). Do not hand-edit.\n',tag,S);
fprintf(fid,'\\begin{table}[htbp]\n\\centering\n\\caption{%s (mean$\\pm$SD over %d seeds). Wilcoxon $p$ compares Proposed vs.\\ each benchmark; $^{\\ast}$ = significant at the Bonferroni threshold $\\alpha=0.0167$; bold marks the best mean in each row; $r=(n^+-n^-)/(n^++n^-)$ is the sign-based effect size over seeds.}\n',caption,S);
fprintf(fid,'\\label{tab:%s}\n\\small\n\\resizebox{\\textwidth}{!}{\\begin{tabular}{lcccccc}\n\\toprule\n',label);
fprintf(fid,'Metric & Classic & B1 & B2 & Proposed & $p$(vsB1) & $p$(vsB2) \\\\\n\\midrule\n');
for ii=1:numel(metrics)
  st=R.Stats.(metrics{ii}); mu=st.mean; sd=st.sd; pv=st.wilcoxon_p; rb=st.rankbiserial;
  if strcmp(metrics{ii},'energyPerBit'), mu=mu*1e6; sd=sd*1e6; end   % J -> uJ/bit
  order=[1 b1 b2 pIdx]; lab=pretty(metrics{ii}); cells=cell(1,4);
  if contains(lab,'downarrow'), [~,bi]=min(mu(order)); elseif contains(lab,'uparrow'), [~,bi]=max(mu(order)); else, bi=0; end
  for q=1:4
    c=sprintf('%.2f$\\pm$%.2f',mu(order(q)),sd(order(q)));
    if q==bi, c=['\textbf{' sprintf('%.2f',mu(order(q))) '}$\pm$' sprintf('%.2f',sd(order(q)))]; end
    cells{q}=c;
  end
  fprintf(fid,'%s & %s & %s & %s & %s & %.3f%s & %.3f%s \\\\\n',...
    lab, cells{:}, pv(b1),sig(pv(b1)), pv(b2),sig(pv(b2)));
end
% effect-size footnote line
fprintf(fid,'\\midrule\n\\multicolumn{7}{l}{\\footnotesize Sign effect size $r$ (Proposed vs B1) on %s: $%.2f$; vs B2: $%.2f$.}\\\\\n',...
  metrics{1}, R.Stats.(metrics{1}).rankbiserial(b1), R.Stats.(metrics{1}).rankbiserial(b2));
fprintf(fid,'\\bottomrule\n\\end{tabular}}\n\\end{table}\n');
fclose(fid);
end
function s=sig(p), if ~isnan(p)&&p<=0.0167, s='$^{\ast}$'; else, s=''; end, end
