function make_report_fair(tag)
%MAKE_REPORT_FAIR  Turn results/<tag>.mat (from run_fair) into thesis artefacts:
%   ch4_fair.tex       -- equal-K comparison table (mean +/- SD over seeds,
%                         paired Wilcoxon vs Proposed, Bonferroni-corrected)
%   ch4_fair_verdict.tex -- one auto-worded sentence per key metric for
%                         Proposed vs MC-MATD3 (the architecture test).
%   Real data only; nothing is typed by hand.
if nargin<1, tag='fairA'; end
here=fileparts(mfilename('fullpath'));
resdir=fullfile(here,'..','results');
thesis=fullfile(here,'..','output'); if ~exist(thesis,'dir'), mkdir(thesis); end;
R=getfield(load(fullfile(resdir,[tag '.mat'])),'R');
methods=R.methods; mn=R.metricNames; D=R.Data; S=size(D,1);
mi=@(x) find(strcmp(mn,x));
P=find(strcmp(methods,'Proposed'));
nCmp=numel(methods)-1; alpha=0.05/nCmp;            % Bonferroni over comparisons
cols ={'delay','throughput','pdr','fairness','loadVar','handover','cci'};
heads={'Delay (ms)','Thr.\ (Mbps)','PDR','Fairness','Load var.','Handover','CCI (dBm)'};
fmt  ={'%.1f','%.1f','%.3f','%.2f','%.1f','%.3f','%.1f'};
better=[-1 +1 +1 +1 -1 -1 -1];                        % +1 higher is better
pretty=containers.Map({'Proposed','MC-MATD3','B1-MC','B2-MC','Proposed-K1'},...
  {'Proposed ($K{=}3$)','MC-MATD3 ($K{=}3$)','B1-MC ($K{=}3$)',...
   'B2-MC ($K{=}3$)','Proposed-K1 ($K{=}1$)'});

fid=fopen(fullfile(thesis,'ch4_fair.tex'),'w');
fprintf(fid,'%% auto-generated by make_report_fair.m from results/%s.mat\n',tag);
fprintf(fid,['\\begin{table}[htbp]\\centering\n\\caption{Equal-spectrum comparison on '...
 'Scenario~A ($N=10$, %d seeds, mean$\\pm$SD). All learners except Proposed-K1 use the '...
 'same $K=3$ channels, isolating the contribution of the architecture from that of '...
 'channel count. $^{\\dagger}$: paired Wilcoxon signed-rank test against Proposed '...
 'significant at the Bonferroni-corrected level $\\alpha=%.4f$; bold marks the best mean in each column.}\n'...
 '\\label{tab:ch4_fair}\\footnotesize\\setlength{\\tabcolsep}{3pt}\n'...
 '\\resizebox{\\textwidth}{!}{\\begin{tabular}{l%s}\n\\toprule\nMethod'],S,alpha,repmat('c',1,numel(cols)));
for c=1:numel(cols), fprintf(fid,' & %s',heads{c}); end
fprintf(fid,'\\\\\n\\midrule\n');
for m=[P setdiff(1:numel(methods),P)]
  fprintf(fid,'%s',pretty(methods{m}));
  for c=1:numel(cols)
    k=mi(cols{c}); mu=mean(D(:,m,k)); sd=std(D(:,m,k),0);
    s=sprintf(['%s$\\pm$%s'],sprintf(fmt{c},mu),sprintf(fmt{c},sd));
    allmu=squeeze(mean(D(:,:,k),1)); if better(c)>0, [~,bm]=max(allmu); else, [~,bm]=min(allmu); end
    if m==bm, s=['\textbf{' sprintf(fmt{c},mu) '}$\pm$' sprintf(fmt{c},sd)]; end
    if m~=P
      p=R.Stats.(cols{c}).wilcoxon_p(m);
      if ~isnan(p) && p<alpha, s=[s '$^{\dagger}$']; end
    end
    fprintf(fid,' & %s',s);
  end
  fprintf(fid,'\\\\\n');
  if m==P, fprintf(fid,'\\midrule\n'); end
end
fprintf(fid,'\\bottomrule\n\\end{tabular}}\n\\end{table}\n'); fclose(fid);

% ---- verdict sentences: Proposed vs MC-MATD3 ----
M=find(strcmp(methods,'MC-MATD3'));
fid=fopen(fullfile(thesis,'ch4_fair_verdict.tex'),'w');
fprintf(fid,'%% auto-generated by make_report_fair.m from results/%s.mat\n',tag);
parts={};
for c=1:numel(cols)
  k=mi(cols{c}); a=mean(D(:,P,k)); b=mean(D(:,M,k));
  p=R.Stats.(cols{c}).wilcoxon_p(M);
  if isnan(p), sig='not testable';
  elseif p<alpha, sig='significant';
  else, sig='not significant'; end
  if better(c)*(a-b)>0, dir='better'; else, dir='worse'; end
  parts{end+1}=sprintf(['%s: Proposed %s vs.\\ MC-MATD3 %s (Proposed %s; $p=%.4f$, %s)'],...
     strrep(heads{c},'\ ',' '),sprintf(fmt{c},a),sprintf(fmt{c},b),dir,p,sig); %#ok<AGROW>
end
fprintf(fid,'%s.\n',strjoin(parts,'; '));
fclose(fid);
fprintf('make_report_fair: wrote ch4_fair.tex and ch4_fair_verdict.tex (alpha=%.4f)\n',alpha);
end
