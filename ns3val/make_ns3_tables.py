"""Tables of the packet-level validation for the article and the thesis.
usage: make_ns3_tables.py <results out dir> <article table> <thesis table>"""
import sys, glob, re, os
import numpy as np, pandas as pd
from scipy.stats import wilcoxon
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import matref
OUT, ART, THE = sys.argv[1:4]
ORDER = ['B1', 'B2', 'HeurMC', 'Proposed', 'Hybrid']
def per_seed(L, m):
    S = {}
    for f in glob.glob(f'{OUT}/L{L}/{m}_s*_e*.csv'):
        s = int(re.findall(r'_s(\d+)_e', f)[0]); S.setdefault(s, []).append(pd.read_csv(f).mean())
    return pd.DataFrame({s: pd.DataFrame(v).mean() for s, v in sorted(S.items())}).T
ref, mn = matref.allref()
D = {L: {m: per_seed(L, m) for m in ORDER} for L in ('1.0', '0.3')}
cols = [  # (label, source, column, better, fmt)
    ('Delay', 'mat', 0, 'min', '{:.1f}'), ('Thr.', 'mat', 2, 'max', '{:.1f}'),
    ('Delay', '1.0', 'delay', 'min', '{:.0f}'), ('Pkt.\\ delay', '1.0', 'pktdelay', 'min', '{:.0f}'),
    ('PDR', '1.0', 'pdr', 'max', '{:.3f}'), ('Thr.', '1.0', 'thr', 'max', '{:.1f}'),
    ('Fairness', '1.0', 'fair', 'max', '{:.2f}'), ('Load var.', '1.0', 'loadvar', 'min', '{:.1f}'),
    ('Delay', '0.3', 'delay', 'min', '{:.0f}'), ('Thr.', '0.3', 'thr', 'max', '{:.1f}')]
def vals(m, src, c):
    return ref[m][:, c] if src == 'mat' else D[src][m][c].values
cells = {m: [] for m in ORDER}
for lab, src, c, better, fmt in cols:
    means = {m: float(np.mean(vals(m, src, c))) for m in ORDER}
    best = (min if better == 'min' else max)(means, key=means.get)
    for m in ORDER:
        s = fmt.format(means[m])
        if m == best: s = '\\textbf{' + s + '}'
        if m != 'Hybrid':
            a, b = vals('Hybrid', src, c), vals(m, src, c)
            if not np.allclose(a, b) and wilcoxon(a, b, method='exact').pvalue < 0.0125: s += '$^\\dagger$'
        cells[m].append(s)
def table(names, star, label, cap_method):
    head = ('\\begin{table*}[t]\n\\centering\n' if star else '\\begin{table}[htbp]\n\\centering\n')
    cap = ('\\caption{Packet-level validation in ns-3 on Scenario~A ($N=10$; mean over eight paired seeds, 30 evaluation '
           'episodes per seed). The trained policies and the rule-based components act on an 802.11n mesh with packet-level '
           'medium access, queueing, and forwarding; user trajectories and demands replay the evaluation episodes of the '
           'analytical simulator. Delay is the mean over UAVs of the mean delay of their delivered packets, with 2000\\,ms '
           'for a UAV that delivers no packet in a step; packet delay is the mean over delivered packets (ms); throughput in '
           'Mbps. Bold marks the best value in each column; $^\\dagger$ marks a difference from ' + cap_method +
           ' that is significant (paired exact Wilcoxon signed-rank test, Bonferroni $\\alpha=0.0125$).}\n')
    body = (f'\\label{{{label}}}\n\\footnotesize\n\\setlength{{\\tabcolsep}}{{3pt}}\n\\resizebox{{\\textwidth}}{{!}}{{%\n'
            '\\begin{tabular}{@{}lcc|cccccc|cc@{}}\n\\toprule\n'
            ' & \\multicolumn{2}{c|}{Analytical simulator} & \\multicolumn{6}{c|}{ns-3, nominal load} & \\multicolumn{2}{c}{ns-3, 30\\% load} \\\\\n'
            'Method & ' + ' & '.join(c[0] for c in cols) + ' \\\\\n\\midrule\n')
    for m in ORDER:
        body += names[m] + ' & ' + ' & '.join(cells[m]) + ' \\\\\n'
    body += '\\bottomrule\n\\end{tabular}}\n' + ('\\end{table*}\n' if star else '\\end{table}\n')
    return '% generated by implementation/ns3val/make_ns3_tables.py\n' + head + cap + body
open(ART, 'w').write(table({'B1': 'B1', 'B2': 'B2', 'HeurMC': 'Heur-MC', 'Proposed': '\\lamc{}', 'Hybrid': '\\method{}'},
                           True, 'tab:ns3', '\\method{}'))
open(THE, 'w').write(table({'B1': 'B1', 'B2': 'B2', 'HeurMC': 'Heur-MC', 'Proposed': 'Proposed', 'Hybrid': 'Hybrid'},
                           False, 'tab:ch6_ns3', 'the hybrid configuration'))
for m in ORDER: print(m, cells[m])
