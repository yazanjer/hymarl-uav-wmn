"""Table of the packet-level validation across fleet sizes and scenarios (nominal load) with
the packet delivery ratio at 5% load. usage: make_ns3_cells_table.py <batch2 out> <batch1 out> <article tex> <thesis tex>"""
import sys, glob, re
import numpy as np, pandas as pd
from scipy.stats import wilcoxon
O2, O1, ART, THE = sys.argv[1:5]
ORDER = ['B1', 'B2', 'HeurMC', 'Proposed', 'Hybrid']
def per_seed(d, m, col):
    S = {}
    for f in glob.glob(f'{d}/{m}_s*_e*.csv'):
        s = int(re.findall(r'_s(\d+)_e', f)[0]); S.setdefault(s, []).append(pd.read_csv(f)[col].mean())
    return np.array([np.mean(S[s]) for s in sorted(S)])
def d(cell, L):
    return f'{O1}/L{L}' if (cell == 'A10' and L != '0.05') else f'{O2}/{cell}/L{L}'
CELLS = [('A5', 'A, $N=5$'), ('A10', 'A, $N=10$'), ('A20', 'A, $N=20$'), ('B10', 'B, $N=10$'), ('C10', 'C, $N=10$')]
BLOCKS = [('Delay (ms)', '1.0', 'delay', 'min', '{:.0f}'), ('Throughput (Mbps)', '1.0', 'thr', 'max', '{:.1f}'),
          ('PDR at 5\\% load', '0.05', 'pdr', 'max', '{:.2f}')]
rows = []
for bl, L, col, better, fmt in BLOCKS:
    for k, (c, lab) in enumerate(CELLS):
        v = {m: per_seed(d(c, L), m, col) for m in ORDER}
        mu = {m: v[m].mean() for m in ORDER}
        best = (min if better == 'min' else max)(mu, key=mu.get)
        cells = []
        for m in ORDER:
            s = fmt.format(mu[m]); s = '\\textbf{' + s + '}' if m == best else s
            if m != 'Hybrid' and not np.allclose(v[m], v['Hybrid']) and \
               wilcoxon(v['Hybrid'], v[m], method='exact').pvalue < 0.0125: s += '$^\\dagger$'
            cells.append(s)
        rows.append(((bl if k == 0 else ''), lab, cells))
def table(names, star, label, ref):
    t = ['% generated by implementation/ns3val/make_ns3_cells_table.py',
         '\\begin{table*}[t]' if star else '\\begin{table}[htbp]', '\\centering',
         '\\caption{Packet-level validation in ns-3 across fleet sizes and scenarios (mean over eight paired seeds; 30 '
         'evaluation episodes per seed for A, $N=10$, and 10 for the other settings). Delay and throughput at nominal load; '
         'packet delivery ratio (PDR) at 5\\% of the nominal load. Delay is defined as in Table~\\ref{' + ref + '}. Bold marks '
         'the best value in each row; $^\\dagger$ marks a difference from ' + names['Hybrid'] + ' that is significant (paired '
         'exact Wilcoxon signed-rank test, Bonferroni $\\alpha=0.0125$).}',
         f'\\label{{{label}}}', '\\footnotesize', '\\setlength{\\tabcolsep}{4pt}',
         '\\begin{tabular}{@{}llccccc@{}}', '\\toprule',
         'Metric & Setting & ' + ' & '.join(names[m] for m in ORDER) + ' \\\\', '\\midrule']
    for i, (bl, lab, cells) in enumerate(rows):
        if bl and i: t.append('\\midrule')
        t.append(f'{bl} & {lab} & ' + ' & '.join(cells) + ' \\\\')
    t += ['\\bottomrule', '\\end{tabular}', '\\end{table*}' if star else '\\end{table}']
    return '\n'.join(t) + '\n'
open(ART, 'w').write(table({'B1': 'B1', 'B2': 'B2', 'HeurMC': 'Heur-MC', 'Proposed': '\\lamc{}', 'Hybrid': '\\method{}'},
                           True, 'tab:ns3cells', 'tab:ns3'))
open(THE, 'w').write(table({'B1': 'B1', 'B2': 'B2', 'HeurMC': 'Heur-MC', 'Proposed': 'Proposed', 'Hybrid': 'Hybrid'},
                           False, 'tab:ch6_ns3_cells', 'tab:ch6_ns3'))
for r in rows: print(r)
